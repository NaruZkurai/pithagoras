#!/usr/bin/env bash
# update-runner-node_modules.sh — rebuild the sandbox image with fresh baked app
# deps, then snapshot a NON-ROOT-owned copy of node_modules for THIS repo.
#
# Why a non-root variant: the agent containers run as the workspace owner
# (uid:gid 1000 = image's `runner`, matching this repo's files on this host).
# If the image's `/repo/node_modules` ever ends up root-owned (e.g. via COPY or
# a cache layer), a non-root agent can read but not write it, and npm can't add
# packages. This script extracts the baked node_modules out of the fresh image,
# re-owns it to uid:gid 1000, and publishes it to a repo-specific cache dir
# (gitignored) that deploy tooling can mount into session containers so agents
# always get a writable dependency set.
#
# Usage:
#   scripts/update-runner-node_modules.sh           # rebuild + publish non-root variant
#   scripts/update-runner-node_modules.sh --extract # skip rebuild, just re-snapshot current image
# Env:
#   IMAGE         (default pithagoras-runner-arch:latest)
#   CACHE_DIR     (default $PWD/data/runner-node_modules)
#   NODE_UID:GID  (default 1000:1000, the shared non-root owner)
#   DOCKERFILE    (default docker/runner-arch.dockerfile)
set -euo pipefail
cd "$(dirname "$0")/.."

IMAGE="${IMAGE:-pithagoras-runner-arch:latest}"
DOCKERFILE="${DOCKERFILE:-docker/runner-arch.dockerfile}"
CACHE_DIR="${CACHE_DIR:-$PWD/data/runner-node_modules}"
NONROOT="${NONROOT:-1000:1000}"
REPO_TAG="pithagoras"        # explicit per-repo bucket inside CACHE_DIR

# --- fail fast: never pipe a build/install through tail (masks failure) -------
if [[ "${1:-}" != "--extract" ]]; then
  echo "==> Building image ${IMAGE} with baked app node_modules..."
  docker build -f "$DOCKERFILE" -t "$IMAGE" .
fi

# Derive the image id so the snapshot is traceable back to the exact build.
IMAGE_ID="$(docker images --no-trunc --format '{{.ID}}' "$IMAGE" | head -1)"
[ -n "$IMAGE_ID" ] || { echo "ERROR: could not resolve image id for $IMAGE"; exit 1; }
echo "==> Image id: ${IMAGE_ID}"

# --- extract the image's /repo/node_modules into a temp host copy -------------
TMP="$(mktemp -d /tmp/runner-nm-XXXXXX)"
trap 'rm -rf "$TMP"' EXIT
echo "==> Extracting /repo/node_modules from image..."
if ! docker run --rm -v "$TMP:/out" --entrypoint bash "$IMAGE" \
    -c 'tar -C /repo -cf - node_modules | tar -C /out -xf -'; then
  echo "ERROR: failed to extract repo node_modules from image."
  exit 1
fi
[ -d "$TMP/node_modules" ] || { echo "ERROR: image has no /repo/node_modules — was npm install skipped?"; exit 1; }

# --- re-own root-owned packages to the non-root variant ------------------------
echo "==> Re-owning to non-root ${NONROOT}..."
chown -R "$NONROOT" "$TMP/node_modules" || {
  echo "ERROR: chown to ${NONROOT} failed (need permission on $TMP)."
  exit 1
}
# Guard: anything still owned by uid 0 signals a baked root-owned leftover.
ROOT_OWNED="$(find "$TMP/node_modules" -user 0 2>/dev/null | wc -l)"
echo "==> root-owned files remaining: ${ROOT_OWNED} (should be 0)"
[ "$ROOT_OWNED" -eq 0 ] || { echo "ERROR: ${ROOT_OWNED} files still root-owned — non-root variant is not clean."; exit 1; }

# --- publish into the repo-specific cache dir ----------------------------------
DEST="$CACHE_DIR/$REPO_TAG"
mkdir -p "$DEST"
# Keep the previous snapshot for instant rollback, then move the new one in.
[ -e "$DEST/node_modules" ] && rm -rf "$DEST/node_modules.prev"
[ -e "$DEST/node_modules" ] && mv "$DEST/node_modules" "$DEST/node_modules.prev"
mv "$TMP/node_modules" "$DEST/node_modules"
echo "$IMAGE_ID" > "$DEST/image-id.txt"

echo "==> Published non-root node_modules variant:"
du -sh "$DEST/node_modules"
echo "    owner: $(stat -c '%U:%G (%u:%g)' "$DEST/node_modules")"
echo "    image: ${IMAGE_ID}"

# --- smoke test: native dep loads from the cached copy --------------------------
echo "==> Smoke-testing native better-sqlite3 from the variant..."
SMOKE="$(cd "$DEST" && node -e '
  const db = require("better-sqlite3");
  const d = new db(":memory:");
  d.exec("create table t(a)");
  d.prepare("insert into t values (1)").run();
  console.log("OK " + JSON.stringify(d.prepare("select a from t").get()));
' 2>&1 || true)"
if printf '%s' "$SMOKE" | grep -q '^OK '; then
  echo "    native better-sqlite3 loads from non-root variant: $SMOKE"
else
  echo "WARN: better-sqlite3 did not load from host copy: $SMOKE"
  echo "     (native builds can be host-specific; this is expected if the host"
  echo "      arch/toolchain differs from the image. The image copy still works.)" >&2
fi

echo "==> Done. Mount this variant into agent containers at /repo/node_modules (uid ${NONROOT})."
